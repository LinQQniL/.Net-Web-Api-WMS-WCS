using System;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using MiddlewareDemo.Data;

namespace MiddlewareDemo.Data;

/// <summary>
/// 启动时的数据库自愈器。
///
/// 背景：本项目的迁移历史已与实体模型脱节（实体新增了 Users.Email / Phone / RoleId /
/// State、Menus.LevelCode / ParentName，以及 Roles / RoleMenus / MenuPowers 三张表），
/// 但数据库里尚未生成对应结构，导致登录时报 "42703: 字段 u.Email 不存在"。
///
/// 这里用幂等 SQL 直接补齐结构：
///   - IF NOT EXISTS 判断列/表是否存在，重复执行安全
///   - 不依赖 dotnet-ef 命令行，重启即生效
///   - 补齐后仍调用 Migrate()，让后续正式迁移能正常接管
/// </summary>
public static class DatabaseInitializer
{
	public static async Task InitializeAsync(AppDbContext db, ILogger? logger = null)
	{
		// 1) 先尝试走正式迁移（数据库是全新库时，这一步会把所有表建好）
		try
		{
			await db.Database.MigrateAsync();
		}
		catch (Exception ex)
		{
			logger?.LogWarning(ex, "执行 EF 迁移失败，转用幂等 SQL 补齐结构");
		}

		// 2) 幂等补齐：缺什么补什么，已存在则跳过
		await EnsureSchemaAsync(db, logger);

		// 3) 补齐种子数据（角色、授权、权限点）
		await SeedRoleDataAsync(db, logger);
	}

	private static async Task EnsureSchemaAsync(AppDbContext db, ILogger? logger)
	{
		// ---------- Users 表新增列 ----------
		await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Users"" ADD COLUMN IF NOT EXISTS ""Phone"" character varying(20);");
		await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Users"" ADD COLUMN IF NOT EXISTS ""Email"" character varying(100);");
		await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Users"" ADD COLUMN IF NOT EXISTS ""RoleId"" integer;");
		await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Users"" ADD COLUMN IF NOT EXISTS ""State"" boolean NOT NULL DEFAULT TRUE;");

		// ---------- Menus 表新增列 ----------
		await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Menus"" ADD COLUMN IF NOT EXISTS ""LevelCode"" character varying(50);");
		await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Menus"" ADD COLUMN IF NOT EXISTS ""ParentName"" character varying(50);");

		// ---------- Roles ----------
		await db.Database.ExecuteSqlRawAsync(@"
CREATE TABLE IF NOT EXISTS ""Roles"" (
    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ""Code"" character varying(50) NOT NULL,
    ""Name"" character varying(50) NOT NULL,
    ""Description"" character varying(200),
    ""State"" boolean NOT NULL DEFAULT TRUE,
    ""CreateTime"" timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);");
		await db.Database.ExecuteSqlRawAsync(@"CREATE UNIQUE INDEX IF NOT EXISTS ""IX_Roles_Code"" ON ""Roles"" (""Code"");");

		// ---------- RoleMenus ----------
		await db.Database.ExecuteSqlRawAsync(@"
CREATE TABLE IF NOT EXISTS ""RoleMenus"" (
    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ""RoleId"" integer NOT NULL,
    ""MenuId"" integer NOT NULL,
    ""Display"" boolean NOT NULL DEFAULT TRUE,
    ""Insert"" boolean NOT NULL DEFAULT FALSE,
    ""Update"" boolean NOT NULL DEFAULT FALSE,
    ""Delete"" boolean NOT NULL DEFAULT FALSE,
    ""Save"" boolean NOT NULL DEFAULT FALSE,
    ""Search"" boolean NOT NULL DEFAULT FALSE,
    ""Export"" boolean NOT NULL DEFAULT FALSE,
    ""Print"" boolean NOT NULL DEFAULT FALSE,
    ""Import"" boolean NOT NULL DEFAULT FALSE,
    ""Operates"" character varying(500),
    ""CreateTime"" timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);");
		await db.Database.ExecuteSqlRawAsync(@"CREATE UNIQUE INDEX IF NOT EXISTS ""IX_RoleMenus_RoleId_MenuId"" ON ""RoleMenus"" (""RoleId"", ""MenuId"");");
		await db.Database.ExecuteSqlRawAsync(@"CREATE INDEX IF NOT EXISTS ""IX_RoleMenus_MenuId"" ON ""RoleMenus"" (""MenuId"");");

		// ---------- MenuPowers ----------
		await db.Database.ExecuteSqlRawAsync(@"
CREATE TABLE IF NOT EXISTS ""MenuPowers"" (
    ""MenuPowerId"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ""MenuId"" integer NOT NULL,
    ""Code"" character varying(50) NOT NULL,
    ""Name"" character varying(50) NOT NULL,
    ""Description"" character varying(200),
    ""SortOrder"" integer NOT NULL DEFAULT 0,
    ""CreateTime"" timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);");
		await db.Database.ExecuteSqlRawAsync(@"CREATE INDEX IF NOT EXISTS ""IX_MenuPowers_MenuId"" ON ""MenuPowers"" (""MenuId"");");

		// ---------- 外键（先判断约束是否已存在，避免重复报错）----------
		await db.Database.ExecuteSqlRawAsync(@"
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        WHERE c.conname = 'FK_Users_Roles_RoleId' AND t.relname = 'Users'
    ) THEN
        ALTER TABLE ""Users"" ADD CONSTRAINT ""FK_Users_Roles_RoleId""
            FOREIGN KEY (""RoleId"") REFERENCES ""Roles"" (""Id"") ON DELETE SET NULL;
    END IF;
END $$;");

		await db.Database.ExecuteSqlRawAsync(@"
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        WHERE c.conname = 'FK_RoleMenus_Roles_RoleId' AND t.relname = 'RoleMenus'
    ) THEN
        ALTER TABLE ""RoleMenus"" ADD CONSTRAINT ""FK_RoleMenus_Roles_RoleId""
            FOREIGN KEY (""RoleId"") REFERENCES ""Roles"" (""Id"") ON DELETE CASCADE;
    END IF;
END $$;");

		await db.Database.ExecuteSqlRawAsync(@"
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        WHERE c.conname = 'FK_RoleMenus_Menus_MenuId' AND t.relname = 'RoleMenus'
    ) THEN
        ALTER TABLE ""RoleMenus"" ADD CONSTRAINT ""FK_RoleMenus_Menus_MenuId""
            FOREIGN KEY (""MenuId"") REFERENCES ""Menus"" (""Id"") ON DELETE CASCADE;
    END IF;
END $$;");

		await db.Database.ExecuteSqlRawAsync(@"
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        WHERE c.conname = 'FK_MenuPowers_Menus_MenuId' AND t.relname = 'MenuPowers'
    ) THEN
        ALTER TABLE ""MenuPowers"" ADD CONSTRAINT ""FK_MenuPowers_Menus_MenuId""
            FOREIGN KEY (""MenuId"") REFERENCES ""Menus"" (""Id"") ON DELETE CASCADE;
    END IF;
END $$;");

		// ---------- 回填 Menus 的层级编码 ----------
		await db.Database.ExecuteSqlRawAsync(@"UPDATE ""Menus"" SET ""LevelCode"" = ""Id""::text WHERE ""LevelCode"" IS NULL AND ""ParentId"" IS NULL;");

		await db.Database.ExecuteSqlRawAsync(@"
UPDATE ""Menus"" c
SET ""LevelCode"" = p.""LevelCode"" || '.' || c.""SortOrder""::text,
    ""ParentName"" = p.""Name""
FROM ""Menus"" p
WHERE c.""ParentId"" = p.""Id""
  AND (c.""LevelCode"" IS NULL OR c.""ParentName"" IS NULL);");

		logger?.LogInformation("数据库结构同步完成");

		// 修正自增序列：显式插入 Id=1/2 后，序列仍停在 1，
		// 后续正常插入会撞主键，这里把序列推到实际最大值之后
		await db.Database.ExecuteSqlRawAsync(@"
SELECT setval(
    pg_get_serial_sequence('""Roles""', 'Id'),
    GREATEST(COALESCE((SELECT MAX(""Id"") FROM ""Roles""), 0), 1)
);");
	}

	private static async Task SeedRoleDataAsync(AppDbContext db, ILogger? logger)
	{
		// 角色
		await db.Database.ExecuteSqlRawAsync(@"
INSERT INTO ""Roles"" (""Id"", ""Code"", ""Name"", ""Description"", ""State"")
VALUES
    (1, 'Admin', '超级管理员', '拥有全部菜单与操作权限', TRUE),
    (2, 'Warehouse', '仓库作业员', '只负责入库、出库与库存操作', TRUE)
ON CONFLICT (""Id"") DO NOTHING;");

		// 管理员账号绑定角色
		await db.Database.ExecuteSqlRawAsync(@"UPDATE ""Users"" SET ""RoleId"" = 1 WHERE ""RoleId"" IS NULL;");

		// 超级管理员：全部菜单
		await db.Database.ExecuteSqlRawAsync(@"
INSERT INTO ""RoleMenus"" (""RoleId"", ""MenuId"", ""Display"", ""Insert"", ""Update"", ""Delete"", ""Save"", ""Search"", ""Export"", ""Print"", ""Import"")
SELECT 1, m.""Id"", TRUE, TRUE, TRUE, TRUE, TRUE, TRUE, TRUE, TRUE, TRUE
FROM ""Menus"" m
ON CONFLICT (""RoleId"", ""MenuId"") DO NOTHING;");

		// 仓库作业员：仅业务菜单
		await db.Database.ExecuteSqlRawAsync(@"
INSERT INTO ""RoleMenus"" (""RoleId"", ""MenuId"", ""Display"", ""Insert"", ""Update"", ""Delete"", ""Save"", ""Search"", ""Export"", ""Print"", ""Import"")
SELECT 2, m.""Id"", TRUE, TRUE, TRUE, FALSE, TRUE, TRUE, TRUE, FALSE, FALSE
FROM ""Menus"" m
WHERE m.""Id"" IN (1, 2, 3, 4, 10, 11, 20, 21, 30, 31, 32)
ON CONFLICT (""RoleId"", ""MenuId"") DO NOTHING;");

		// 权限点字典：为每个菜单补齐常用权限（幂等）
		await db.Database.ExecuteSqlRawAsync(@"
INSERT INTO ""MenuPowers"" (""MenuId"", ""Code"", ""Name"", ""SortOrder"")
SELECT m.""Id"", p.code, p.name, p.sort_order
FROM ""Menus"" m
CROSS JOIN (VALUES
    ('view',   '查看', 1),
    ('insert', '新增', 2),
    ('update', '修改', 3),
    ('delete', '删除', 4),
    ('export', '导出', 5),
    ('import', '导入', 6)
) AS p(code, name, sort_order)
WHERE NOT EXISTS (
    SELECT 1 FROM ""MenuPowers"" mp
    WHERE mp.""MenuId"" = m.""Id"" AND mp.""Code"" = p.code
);");

		logger?.LogInformation("角色权限种子数据同步完成");
	}
}
